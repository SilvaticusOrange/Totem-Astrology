import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const manifestPath = path.join(root, 'assets/images/totems/composited/MANIFEST.txt');
const outPath = path.join(root, 'app/lib/totem-image-registry.ts');

const filenames = fs
  .readFileSync(manifestPath, 'utf8')
  .trim()
  .split('\n')
  .map((line) => line.trim())
  .filter(Boolean);

const entries = filenames.map((filename) => {
  const key = filename.replace(/\.png$/, '');
  return `  '${key}': require('../../assets/images/totems/composited/${filename}'),`;
});

const contents = `// Auto-generated by scripts/generate-totem-image-registry.mjs — do not edit by hand.
// Regenerate: npm run app:sync-totems
import type { ImageSourcePropType } from 'react-native';

export const TOTEM_IMAGE_REGISTRY: Record<string, ImageSourcePropType> = {
${entries.join('\n')}
};
`;

fs.writeFileSync(outPath, contents);
console.log(`Wrote ${outPath} (${filenames.length} totem images)`);
