const SORTED_BY_CODE_LENGTH = [...COUNTRY_DIAL_CODES].sort(
  (a, b) => b.code.length - a.code.length
);

export function fillDialCodeSelect(select, selectedCode = '1') {
  if (!select) return;
  const current = selectedCode || '1';
  select.replaceChildren();
  for (const entry of COUNTRY_DIAL_CODES) {
    const option = document.createElement('option');
    option.value = entry.code;
    option.textContent = entry.label;
    if (entry.code === current) option.selected = true;
    select.appendChild(option);
  }
}

export function combinePhone(dialCode, localNumber) {
  const local = String(localNumber || '').replace(/\D+/g, '');
  if (!local) return '';
  const code = String(dialCode || '').replace(/\D+/g, '') || '1';
  // Avoid doubling the country code if the user typed it into the number field.
  if (local.startsWith(code) && local.length > code.length + 3) {
    return local;
  }
  return `${code}${local}`;
}

export function splitPhone(fullDigits) {
  const digits = String(fullDigits || '').replace(/\D+/g, '');
  if (!digits) return { code: '1', local: '' };
  for (const entry of SORTED_BY_CODE_LENGTH) {
    if (digits.startsWith(entry.code) && digits.length > entry.code.length) {
      return { code: entry.code, local: digits.slice(entry.code.length) };
    }
  }
  return { code: '1', local: digits };
}
